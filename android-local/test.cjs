const assert=require('node:assert/strict');
const fs=require('node:fs');
const os=require('node:os');
const path=require('node:path');
const crypto=require('node:crypto');
const {openBackend}=require('./storage.cjs');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'captura-test-'));
const file=path.join(dir,'test.sqlite');
let b=openBackend(file);
try {
  assert.equal(b.setup('test-password','capture-key'),true);
  assert.equal(b.setup('different','different'),false);
  const call=(name,...args)=>b.call(name,args);
  assert.throws(()=>call('login','admin','wrong'),/incorrectos/);
  const admin=call('login','admin','test-password');
  const user=call('authorizeCaptureKey','capture-key',crypto.randomUUID());
  assert.throws(()=>call('adminSaveLine',user.token,{name:'Forbidden'}),/permiso/);
  call('adminSaveLine',admin.token,{name:'Línea 1,Línea 2'});
  call('adminSaveRoute',admin.token,{name:'Ruta 1,Ruta 2'});
  let app=call('getAppData',user.token,{line:'Línea 1'});
  const routeId=app.routes[0].id;
  const payload={operationId:crypto.randomUUID(),epoch:app.epoch,line:'Línea 1',routeId,mta:'0',mtb:'',complete:true};
  const first=call('saveEntry',user.token,payload);
  assert.equal(first.entry.mta,0);assert.equal(first.entry.mtb,'');
  call('saveEntry',user.token,payload);
  assert.equal(call('getAppData',user.token,{line:'Línea 1'}).history.length,1);
  b.close();b=openBackend(file);
  call('saveEntry',user.token,payload);
  app=call('getAppData',user.token,{line:'Línea 1'});
  assert.equal(app.history.length,1,'persistent deduplication across restart');
  assert.deepEqual(Array.from(app.completedRouteIds),[routeId]);
  assert.equal(app.history[0].date,first.entry.date);
  assert.throws(()=>call('saveEntry',user.token,{...payload,mta:'9'}),/reutilizado/);
  const snapshot=JSON.stringify(call('getAdminDashboard',admin.token,{}));
  assert.throws(()=>call('adminSaveLine',admin.token,{name:'New,Línea 1'}),/existe/);
  assert.equal(call('getAdminDashboard',admin.token,{}).lines.length,2,'failed operation rolls back');
  call('saveEntry',user.token,{...payload,operationId:crypto.randomUUID(),id:first.entry.id,mta:'',mtb:'7'});
  assert.equal(call('getAppData',user.token,{line:'Línea 1'}).lineTotals.mtb,7);
  assert.match(call('exportEntries',admin.token),/Ruta 1/);
  call('setCaptureEnabled',admin.token,false);
  assert.throws(()=>call('saveEntry',user.token,{...payload,operationId:crypto.randomUUID()}),/PAUSED/);
  call('setCaptureEnabled',admin.token,true);
  call('deleteEntry',user.token,first.entry.id);
  call('saveEntry',user.token,payload);
  assert.equal(call('getAppData',user.token,{line:'Línea 1'}).history.length,0);
  call('resetCapture',admin.token);
  assert.throws(()=>call('saveEntry',user.token,payload),/RESET/);
  call('adminSaveCaptureKey',admin.token,'new-key');
  assert.throws(()=>call('getAppData',user.token,{}),/modificada/);
  const capture=call('authorizeCaptureKey','new-key',crypto.randomUUID());
  const secondAdmin=call('login','admin','test-password');
  const credentials={username:'supervisor',currentPassword:'test-password',newPassword:'new-password-123',confirmPassword:'new-password-123'};
  assert.throws(()=>call('adminUpdateCredentials',capture.token,credentials),/permiso/);
  assert.throws(()=>call('adminUpdateCredentials','invalid',credentials),/sesión/);
  assert.throws(()=>call('adminUpdateCredentials',admin.token,{...credentials,currentPassword:'incorrect'}),/actual es incorrecta/);
  assert.throws(()=>call('adminUpdateCredentials',admin.token,{...credentials,confirmPassword:'mismatch'}),/no coinciden/);
  assert.throws(()=>call('adminUpdateCredentials',admin.token,{...credentials,newPassword:'short',confirmPassword:'short'}),/6 a 128/);
  assert.throws(()=>call('adminUpdateCredentials',admin.token,{...credentials,username:'bad user'}),/usuario debe/);
  call('adminUpdateCredentials',admin.token,credentials);
  assert.throws(()=>call('getAdminDashboard',admin.token,{}),/sesión/);
  assert.throws(()=>call('getAdminDashboard',secondAdmin.token,{}),/sesión/);
  assert.throws(()=>call('login','admin','test-password'),/incorrectos/);
  assert.throws(()=>call('login','supervisor','test-password'),/incorrectos/);
  call('getAppData',capture.token,{});
  b.close();b=openBackend(file);
  assert.throws(()=>call('getAdminDashboard',secondAdmin.token,{}),/sesión/);
  const updated=call('login','supervisor','new-password-123');
  call('adminUpdateCredentials',updated.token,{username:'supervisor2',currentPassword:'new-password-123',newPassword:'',confirmPassword:''});
  const renamed=call('login','supervisor2','new-password-123');
  call('adminUpdateCredentials',renamed.token,{username:'',currentPassword:'new-password-123',newPassword:'abc123',confirmPassword:'abc123'});
  call('login','supervisor2','abc123');
  const loginRows=b.db.prepare("SELECT data FROM rows WHERE sheet='Login'").all();
  assert.ok(loginRows.some(r=>r.data.includes('scrypt$')));
  assert.ok(loginRows.every(r=>!r.data.includes('abc123')));
  assert.equal(b.db.prepare('PRAGMA integrity_check').get().integrity_check,'ok');
  console.log('PASS admin credentials: current-password verification, validation, permissions, session revocation, restart, rename-only, password-only, capture access preserved, salted hash');
  console.log('PASS: auth, permissions, catalogs, transaction rollback, zero/blank, completion, retry, restart, edit/delete, pause, reset, CSV, key rotation, SQLite integrity');
} finally {b.close();fs.rmSync(dir,{recursive:true,force:true});}
